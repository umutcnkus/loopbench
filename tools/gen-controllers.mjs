// Collect controller templates into src/generated/controllers.js
import fs from 'node:fs';
import path from 'node:path';
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const dir = path.join(root, 'src/controllers');
const out = {};
for (const plant of fs.readdirSync(dir).sort()) {
  const pdir = path.join(dir, plant);
  if (!fs.statSync(pdir).isDirectory()) continue;
  out[plant] = [];
  for (const f of fs.readdirSync(pdir).filter((f) => f.endsWith('.js')).sort()) {
    const code = fs.readFileSync(path.join(pdir, f), 'utf8');
    const name = (code.match(/^\/\/\s*@name\s+(.+)$/m) || [])[1]?.trim() || f;
    const isDefault = /^\/\/\s*@default\s*$/m.test(code);
    const ic = (code.match(/^\/\/\s*@ic\s+([\w-]+)\s*$/m) || [])[1];
    const body = code.replace(/^\/\/\s*@name.*\n/m, '').replace(/^\/\/\s*@default\s*\n/m, '').replace(/^\/\/\s*@ic.*\n/m, '');
    out[plant].push({ id: f.replace(/^\d+-/, '').replace(/\.js$/, ''), name, isDefault, ...(ic ? { ic } : {}), code: body });
  }
}
fs.mkdirSync(path.join(root, 'src/generated'), { recursive: true });
fs.writeFileSync(path.join(root, 'src/generated/controllers.js'), '// generated by tools/gen-controllers.mjs\nexport default ' + JSON.stringify(out, null, 1) + ';\n');
console.log('controllers:', Object.entries(out).map(([k, v]) => `${k}(${v.length})`).join(' '));
